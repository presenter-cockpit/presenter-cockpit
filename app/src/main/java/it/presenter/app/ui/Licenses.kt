package it.presenter.app.ui

import android.content.Context
import it.presenter.app.R

/** License kinds, in the order they are shown. */
enum class LicenseKind { APACHE, MIT, BSD, ISC, OFL, OTHER, TERMS }

/**
 * The components sharing a license: [families] is the summary (families such as "AndroidX" instead of the
 * single modules, then the others by name), [components] the complete list, [text] the license text with
 * the components' own copyright notices.
 */
class LicenseGroup(val kind: LicenseKind, val families: List<String>, val components: List<String>, val text: String)

/**
 * Licenses of the components included in the app, grouped by license (one text per license plus each
 * component's copyright notices is enough). The list is generated by the oss-licenses plugin from the
 * Gradle dependencies (`res/raw/third_party_license_metadata`: lines "start:length name", and
 * `third_party_licenses` with the texts), one entry per module and with duplicates (ML Kit brings its own
 * copies of AndroidX under other names: "AndroidX core library" = "Core"), which are merged here. For
 * many libraries the plugin only has the license URL: Apache 2.0, BSD and MIT require the text, though,
 * so known URLs are replaced with the full texts of `res/raw/license_texts.txt` ("=== key" sections).
 * libvterm is inside termlib's native library and has no POM: it is added by hand, like the handwriting
 * font in `res/font` ([FONTS]: its copyright notice and the SIL Open Font License text).
 */
object Licenses {
    /** URL in the POM → (kind, key of the full text in `license_texts.txt`, name suffix). */
    private val KNOWN = listOf(
        "apache.org/licenses/LICENSE-2.0" to Triple(LicenseKind.APACHE, null, ""),
        "mwiede/jsch/blob/master/LICENSE.jBCrypt" to Triple(LicenseKind.ISC, "jbcrypt", " (jBCrypt)"),
        "mwiede/jsch/blob/master/LICENSE.txt" to Triple(LicenseKind.BSD, "jsch", ""),
        "bouncycastle.org/licence" to Triple(LicenseKind.MIT, "bouncycastle", ""),
        "github.com/neovim/libvterm" to Triple(LicenseKind.MIT, "libvterm", ""),
        "developers.google.com/ml-kit/terms" to Triple(LicenseKind.TERMS, null, ""),
        "developer.android.com/studio/terms" to Triple(LicenseKind.TERMS, null, ""),
    )

    /** Summary families: name → rule on the module name. Excluded components stay by name. */
    private val FAMILIES = listOf(
        "AndroidX" to Regex(
            "^(AndroidX|androidx\\.|Android Support|Android (Arch|Room|DB|Graphics|Tracing|App Startup|Resource|WorkManager)|" +
                "Compose|Lifecycle|LiveData|Activity|Saved ?State|Ink |Navigation ?Event|WindowManager|Emoji2|" +
                "[Ff]ragment|[Cc]ollections|Core|Biometric|ConstraintLayout|Graphics|Motion Prediction|" +
                "Profile Installer|Transition|Custom View|DynamicAnimation|Experimental annotation|Annotation$|" +
                "AppCompat|VersionedParcelable)",
        ),
        "Kotlin, kotlinx" to Regex("^(Kotlin|kotlinx|Parcelize|JetBrains)"),
        "Google Play services, Firebase, ML Kit" to
            Regex("^(play-services|[Ff]irebase|transport-|SafeParcelable|gsfclient|common$|digital-ink|mobiledatadownload)"),
        "Google: Guava, Gson, Dagger, gRPC…" to Regex(
            "^(Guava|Gson|Dagger|gRPC|Error Prone|error-prone|Google (Auto|HTTP)|J2ObjC|JsInterop|HighwayHash|OpenCensus|apksig)",
        ),
        "JSR, JSpecify, javax.inject" to Regex("^(JSR|JSpecify|javax\\.inject|Jakarta Inject|java_annotations)"),
        "OkHttp, Okio" to Regex("^(okhttp|Okio)"),
        "Bouncy Castle" to Regex("^Bouncy Castle"),
        // "kotlin" (lowercase) is the Kotlin module of Protocol Buffers, with its own license.
        "Protocol Buffers" to Regex("^(Protocol Buffers|kotlin$)"),
        "Android SDK" to Regex("^Android SDK"),
    )

    /** Fonts bundled in `res/font` (unmodified, from Google Fonts) with the copyright notice of their license file. */
    private val FONTS = listOf(
        "Indie Flower" to "Copyright 2010 The Indie Flower Authors (kimberlygeswein.com)",
    )

    /** Last line of the entries of [FONTS]: what [resolve] recognizes them by. */
    private const val OFL_MARK = "SIL Open Font License 1.1"

    /** A "plain" Apache text is shorter: beyond this there is something else (Kotlin, J2ObjC) and it is all kept. */
    private const val PLAIN_APACHE_MAX = 12_000

    fun load(context: Context): List<LicenseGroup> {
        val res = context.resources
        val metadata = res.openRawResource(R.raw.third_party_license_metadata).use { it.readBytes().decodeToString() }
        val data = res.openRawResource(R.raw.third_party_licenses).use { it.readBytes() }
        val full = res.openRawResource(R.raw.license_texts).use { it.readBytes().decodeToString() }
        return build(metadata, data, full)
    }

    internal fun build(metadata: String, data: ByteArray, fullTexts: String): List<LicenseGroup> {
        val full = sections(fullTexts)
        val entries = mutableListOf<Pair<String, String>>()
        for (line in metadata.lineSequence()) {
            val space = line.indexOf(' ')
            val colon = line.indexOf(':')
            if (space < 0 || colon !in 1 until space) continue
            val start = line.substring(0, colon).toIntOrNull() ?: continue
            val length = line.substring(colon + 1, space).toIntOrNull() ?: continue
            if (start < 0 || length < 0 || start + length > data.size) continue
            entries += line.substring(space + 1).trim() to data.decodeToString(start, start + length).trim()
        }
        entries += "libvterm (termlib)" to "https://github.com/neovim/libvterm/blob/master/LICENSE"
        for ((font, notice) in FONTS) entries += "$font (font)" to "$notice\n$OFL_MARK"

        // AndroidX duplicates: "AndroidX lifecycle runtime library" becomes "Lifecycle Runtime", if present.
        fun key(name: String) = name.lowercase().removePrefix("androidx ").removeSuffix(" library").filter { it.isLetterOrDigit() }
        val short = entries.map { it.first }.filterNot { it.startsWith("AndroidX ") }.associateBy(::key)
        fun nameOf(name: String): String = if (name.startsWith("AndroidX ")) short[key(name)] ?: name else name

        // kind → (notice or text → names), plus the names of each kind.
        val notices = LinkedHashMap<LicenseKind, LinkedHashMap<String, MutableSet<String>>>()
        val members = LinkedHashMap<LicenseKind, MutableSet<String>>()
        for ((raw, text) in entries) {
            val (kind, notice, suffix) = resolve(text, full)
            val name = nameOf(raw) + suffix
            members.getOrPut(kind) { linkedSetOf() } += name
            if (notice.isNotEmpty()) notices.getOrPut(kind) { LinkedHashMap() }.getOrPut(notice) { linkedSetOf() } += name
        }
        return LicenseKind.entries.mapNotNull { kind ->
            val all = members[kind] ?: return@mapNotNull null
            val parts = notices[kind].orEmpty().map { (notice, who) ->
                // A few names are listed; many (45 AndroidX modules with the same notice) become families.
                "— ${(if (who.size <= 4) who.toList() else families(who)).joinToString(", ")} —\n$notice"
            }
            // One license text for the whole group, then the notices.
            val shared = when (kind) {
                LicenseKind.APACHE -> full["apache-2.0"]
                LicenseKind.OFL -> full["ofl-1.1"]
                else -> null
            }
            val text = (listOfNotNull(shared) + parts).joinToString("\n\n")
            LicenseGroup(kind, families(all), all.sortedBy { it.lowercase() }, text)
        }
    }

    /** Summary: the families present, in the order of [FAMILIES], then the other components by name. */
    private fun families(names: Collection<String>): List<String> {
        val found = linkedSetOf<String>()
        val rest = mutableListOf<String>()
        for (name in names) {
            val family = FAMILIES.firstOrNull { it.second.containsMatchIn(name) }?.first
            if (family != null) found += family else rest += name
        }
        return FAMILIES.map { it.first }.filter { it in found } + rest.sortedBy { it.lowercase() }
    }

    /**
     * (kind, notice to show, name suffix) of a plugin text. A known URL becomes the full text; for Apache only
     * what precedes the license counts (the copyright line), the license text is shown once for the whole group.
     */
    private fun resolve(text: String, full: Map<String, String>): Triple<LicenseKind, String, String> {
        if (text.lines().size == 1 && text.startsWith("http")) {
            val known = KNOWN.firstOrNull { it.first in text }?.second ?: return Triple(LicenseKind.OTHER, text, "")
            val notice = if (known.first == LicenseKind.APACHE) "" else known.second?.let { full[it] } ?: text
            return Triple(known.first, notice, known.third)
        }
        if (text.endsWith(OFL_MARK)) return Triple(LicenseKind.OFL, text.removeSuffix(OFL_MARK).trim(), "")
        val kind = when {
            "Apache License" in text && "Version 2.0" in text -> LicenseKind.APACHE
            "Redistribution and use in source and binary forms" in text -> LicenseKind.BSD
            "Permission is hereby granted" in text -> LicenseKind.MIT
            "Permission to use, copy, modify, and/or distribute" in text -> LicenseKind.ISC
            "SOFTWARE DEVELOPMENT KIT" in text -> LicenseKind.TERMS
            else -> LicenseKind.OTHER
        }
        if (kind != LicenseKind.APACHE || text.length > PLAIN_APACHE_MAX) return Triple(kind, text, "")
        val lines = text.lines()
        val at = lines.indexOfFirst { "Apache License" in it }.takeIf { it >= 0 } ?: lines.size
        return Triple(kind, lines.take(at).joinToString("\n").trim(), "")
    }

    /** "=== key" sections of `license_texts.txt`. */
    internal fun sections(text: String): Map<String, String> {
        val out = mutableMapOf<String, String>()
        var key: String? = null
        val body = StringBuilder()
        fun flush() { key?.let { out[it] = body.toString().trim() }; body.clear() }
        for (line in text.lineSequence()) {
            if (line.startsWith("=== ")) { flush(); key = line.removePrefix("=== ").trim() } else body.appendLine(line)
        }
        flush()
        return out
    }
}
